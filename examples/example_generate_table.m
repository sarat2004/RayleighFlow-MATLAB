%% EXAMPLE_GENERATE_TABLE
% Demonstration of Rayleigh-flow property-table generation.

clear;
clc;

%--------------------------------------------------------------
% Input
%--------------------------------------------------------------

gamma = 1.4;

M = [ ...
    0.2
    0.5
    0.8
    1.0
    1.2
    1.5
    2.0
    3.0
    5.0
];

%--------------------------------------------------------------
% Generate table
%--------------------------------------------------------------

rayleighTable = createTable(M, gamma);

%--------------------------------------------------------------
% Display
%--------------------------------------------------------------

disp("Rayleigh Flow Property Table");
disp("--------------------------------------------");
disp(rayleighTable);